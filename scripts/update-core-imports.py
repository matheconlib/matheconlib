"""Generate or check the public MathEconLib import indices from the Git index."""

import argparse
from collections import defaultdict
from pathlib import Path
import re
import subprocess
import sys

LIBRARY = Path("MathEconLib")
UMBRELLA = LIBRARY.with_suffix(".lean")
INDEX_DIR = LIBRARY / "Index"
GENERATED = "-- Generated by scripts/update-core-imports.py."
HEADER = """/-
Copyright (c) 2026 MathEconLib contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: MathEconLib contributors
-/
"""
MODULE = "module  -- shake: keep-all --deprecated_module: ignore\n\n"


def module_name(path):
    parts = []
    for part in path.with_suffix("").parts:
        if re.fullmatch(r"[A-Za-z_][A-Za-z_0-9']*", part):
            parts.append(part)
        elif "»" in part or not part.isprintable():
            raise ValueError(f"{path}: cannot represent this path as a Lean import")
        else:
            parts.append(f"«{part}»")
    return ".".join(parts)


def render(modules, header=""):
    imports = "".join(f"public import {module}\n" for module in modules)
    return f"{header}{GENERATED}\n{MODULE}{imports}".encode("utf-8")


def expected_lists():
    # Match mk_all --git: new sources enter the inventory after git add and
    # working-tree deletions disappear from the list.
    tracked = subprocess.check_output(["git", "ls-files", "-z", "MathEconLib/*.lean"])
    categories = defaultdict(list)
    for name in set(tracked.decode("utf-8").split("\0")) - {""}:
        path = Path(name)
        if path.is_relative_to(INDEX_DIR) or not path.is_file():
            continue
        category = path.stem if path.parent == LIBRARY else path.parts[1]
        categories[category].append(path)

    expected = {}
    root_imports = []
    for category, paths in sorted(categories.items()):
        modules = sorted(map(module_name, paths))
        if all(path.parent == LIBRARY for path in paths):
            root_imports.extend(modules)
        else:
            index = INDEX_DIR / f"{category}.lean"
            expected[index] = render(modules, HEADER)
            root_imports.append(module_name(index))
    expected[UMBRELLA] = render(root_imports)
    return expected


def update(check):
    if INDEX_DIR.is_symlink() or UMBRELLA.is_symlink():
        raise ValueError("The core import lists must use regular files and directories")
    expected = expected_lists()
    existing = set(INDEX_DIR.rglob("*.lean"))
    for path in sorted(existing):
        if (path.parent != INDEX_DIR or path.is_symlink() or not path.is_file()
                or GENERATED.encode() not in path.read_bytes().splitlines()[:7]):
            raise ValueError(f"{path}: reserved for generated import indices")
    stale = [path for path, content in sorted(expected.items())
             if not path.is_file() or path.read_bytes() != content]
    obsolete = sorted(existing - expected.keys())

    for path in stale:
        print(f"{path}: {'stale or missing' if check else 'regenerating'}")
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected[path])
    for path in obsolete:
        print(f"{path}: {'obsolete' if check else 'removing obsolete index'}")
        if not check:
            path.unlink()
    return int(check and bool(stale or obsolete))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without changing files")
    args = parser.parse_args()
    try:
        return update(args.check)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
